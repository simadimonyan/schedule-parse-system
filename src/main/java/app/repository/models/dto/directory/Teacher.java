package app.repository.models.dto.directory;

import lombok.Data;

import java.io.Serializable;

/**
 * Преподаватель расписания.
 *
 * <p>Как и {@link Group}, не сущность: владелец справочника — мастер-сервис. Парсер знает
 * преподавателя только строкой «Фамилия И.О.», поэтому она и остаётся ключом, по которому
 * строка расписания связывается с записью справочника.
 *
 * <p>Кафедра приходит из мастера отдельным справочником и в представлении преподавателя не
 * возвращается, поэтому поле остаётся пустым — как и в прежней таблице-реплике, где его
 * никто не заполнял. Оно сохранено, чтобы не менять форму ответа API.
 */
@Data
public class Teacher implements Serializable {

    /** Идентификатор преподавателя в справочнике мастер-сервиса. */
    private Long id;

    /** «Фамилия И.О.» — так преподаватель записан в файле расписания. */
    private String label;

    // кафедра
    private String department;

}
