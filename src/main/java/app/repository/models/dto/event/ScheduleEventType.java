package app.repository.models.dto.event;

/**
 * Что произошло с расписанием.
 *
 * <p>Перечисление — публичный контракт сервиса, а не его внутреннее дело: по нему подписчики
 * решают, что им делать с сообщением. Значения не переименовываются и не удаляются: имя
 * уходит в тело события строкой, и переименованное перестанет узнаваться у всех, кто уже
 * слушает топик. Добавлять новые — можно: незнакомое значение потребитель пропускает.
 *
 * <p>Событий, которых здесь нет, сервис не публикует намеренно. Черновик, заведённый
 * {@code VersionService.draft()}, снаружи не виден: клиентам он ничего не меняет, пока его не
 * опубликовали, а публикация — это уже {@link #VERSION_PUBLISHED}.
 */
public enum ScheduleEventType {

    /**
     * Разбор файла заменил расписание перечисленных групп внутри версии.
     *
     * <p>Не значит «клиенты увидели новое»: пока открыт черновик, разбор пишет в него, а
     * выдача остаётся на прежней активной версии.
     */
    VERSION_PARSED,

    /** Пары поставлены или заменены поячеечно — правка из редактора, а не загрузка файла. */
    SCHEDULE_UPDATED,

    /**
     * Версия стала активной: именно ею теперь отвечают на запросы.
     *
     * <p>Самое крупное событие сервиса — меняется всё расписание разом, поэтому подписчику
     * стоит считать устаревшим весь свой снимок, а не отдельные группы.
     */
    VERSION_PUBLISHED,

    /** Версия удалена вместе со всем, что к ней относилось. */
    VERSION_DISCARDED,

    /** Заведено изменение расписания — перенос, отмена, замена или разовая пара. */
    CHANGE_CREATED,

    /** Изменение расписания отредактировано. */
    CHANGE_UPDATED,

    /** Изменение расписания снято: паре возвращён её обычный вид. */
    CHANGE_DELETED,

    /** Правлена сетка звонков версии — время пар сдвинулось. */
    SLOTS_UPDATED,

    /** Правлен график занятости преподавателя. */
    WORK_SCHEDULE_UPDATED,

    /**
     * Переключена чётность недели.
     *
     * <p>Расписание при этом не менялось — сменилось то, какую его половину показывают.
     * Версии у события нет: чётность одна на сервис.
     */
    WEEK_SWAPPED

}
