package app.repository.models.entity;

/**
 * Что случилось с парой.
 *
 * <p>Изменение — не редактирование строки расписания, а отдельная запись поверх неё: пара
 * остаётся на месте, а поверх ложится «перенесена», «отменена» или «замена преподавателя».
 * Так видно и то, как было, и то, как стало, — без чего журнал изменений превратился бы в
 * набор разниц без исходника.
 */
public enum ChangeType {

    /** Пара перенесена в другой слот или на другую дату. */
    MOVE,

    /** Пара отменена и в выдаче не появляется. */
    CANCEL,

    /** Заменены преподаватель, аудитория или предмет — слот прежний. */
    REPLACE,

    /** Разовая пара, которой в исходном расписании не было. */
    ADD

}
